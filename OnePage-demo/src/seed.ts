function ago(hours: number) {
  return new Date(Date.now() - hours * 3600_000).toISOString()
}

function user(partial: Omit<Account, 'coverUrl' | 'avatarUrl' | 'stats' | 'followedByMe'> & { avatar?: string; cover?: string }): Account {
  const avatar = partial.avatar || avatarUrl(partial.userId, partial.nickname)
  const cover = partial.cover || bannerUrl(partial.userId)
  return {
    ...partial,
    avatarUrl: avatar,
    coverUrl: cover,
    followedByMe: false,
    stats: { followingCount: 0, followerCount: 0, likeReceivedCount: 0, favoriteReceivedCount: 0 },
  }
}

function post(p: Omit<PostRow, 'likedByMe' | 'favoritedByMe' | 'media' | 'coverUrl' | 'author'> & { cover?: string; media?: PostRow['media']; author: PostRow['author'] }): PostRow {
  const cover =
    p.cover || (p.postType === 'text' ? '' : coverForNote(p.title, p.body, p.category, p.postId))
  const mediaUrl = p.postType === 'video' ? videoForNote(p.title, p.body, p.category, p.postId) : cover
  return {
    ...p,
    coverUrl: cover,
    likedByMe: false,
    favoritedByMe: false,
    media: p.media || (cover
      ? [{ mediaId: `m_${p.postId}`, url: mediaUrl, mimeType: p.postType === 'video' ? 'video/mp4' : 'image/jpeg', role: 'cover' }]
      : []),
    takenDown: p.takenDown ?? false,
  }
}

